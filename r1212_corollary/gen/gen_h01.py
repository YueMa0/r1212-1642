"""Generate the Lean data and branch modules for `no K8 in N(0) ∩ N(1)` of P_797."""
import os
from pathlib import Path
import shutil
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import search_model as m


def write_outputs(out_dir, outputs):
    """Stage the complete UTF-8/LF batch before replacing any destination.

    Each replacement is atomic. On a caught publication error, restore files
    already replaced (and remove newly created files). This is not a filesystem
    transaction across process crashes. If rollback itself fails, keep the
    staging directory and report its recovery files instead of deleting them.
    Do not run concurrent generators against the same output directory.
    """
    out_dir = Path(out_dir).resolve(strict=True)
    if not out_dir.is_dir():
        raise NotADirectoryError(out_dir)
    texts = {}
    for name, text in outputs.items():
        if Path(name).name != name or name in (".", ".."):
            raise ValueError(f"not an output filename: {name!r}")
        text = text.replace("\r\n", "\n").replace("\r", "\n")
        # Validate the entire batch before opening even a temporary output.
        text.encode("utf-8")
        texts[name] = text
        target = out_dir / name
        if target.is_symlink() or (target.exists() and not target.is_file()):
            raise ValueError(f"output is not a regular file: {target}")

    stage = Path(tempfile.mkdtemp(prefix=".gen_h01-", dir=out_dir))
    keep_recovery_files = False
    replaced = []
    try:
        fresh = stage / "new"
        backup = stage / "original"
        fresh.mkdir()
        backup.mkdir()
        for name, text in texts.items():
            with (fresh / name).open("w", encoding="utf-8", newline="\n") as stream:
                stream.write(text)
                stream.flush()
                os.fsync(stream.fileno())
        # Finish all backups before publishing the first generated file.
        for name in texts:
            target = out_dir / name
            if target.exists():
                shutil.copy2(target, backup / name)
        for name in texts:
            os.replace(fresh / name, out_dir / name)
            replaced.append(name)
    except BaseException as error:
        rollback_errors = []
        for name in reversed(replaced):
            try:
                original = stage / "original" / name
                if original.exists():
                    os.replace(original, out_dir / name)
                else:
                    (out_dir / name).unlink()
            except OSError as rollback_error:
                rollback_errors.append(f"{name}: {rollback_error}")
        if rollback_errors:
            keep_recovery_files = True
            raise RuntimeError(
                f"output rollback failed; recovery files kept at {stage}: "
                + "; ".join(rollback_errors)
            ) from error
        raise
    finally:
        if not keep_recovery_files:
            if stage.resolve().parent != out_dir:
                raise RuntimeError(f"refusing to clean staging directory outside {out_dir}: {stage}")
            shutil.rmtree(stage)


def generate_outputs():
    outputs = {}
    q = 797
    vs = m.h01(1)
    assert len(vs) == 198 and vs == sorted(vs)
    rows = m.rows_for(vs, 1)
    no_clique, branches, stats = m.make(rows)
    full = (1 << 198) - 1
    L, B, br = branches(8, full)
    assert all(no_clique(7, x) for x in br)

    vtx_lit = sum(v << (10 * i) for i, v in enumerate(vs))
    idx = {v: i for i, v in enumerate(vs)}
    idx_lit = sum((idx.get(w, 255)) << (8 * w) for w in range(q))
    rows_lit = sum(r << (256 * i) for i, r in enumerate(rows))
    mask256 = (1 << 256) - 1

    header = "/-\nR(12,12) ≥ 1642: generated by r1212_corollary/gen/gen_h01.py; do not edit by hand.\n-/\n"
    data = header + f'''import RamseyIncrement.R1212.Search

/-!
# The graph `N(0) ∩ N(1)` of `P₇₉₇` as bitsets

The 198 common neighbours of `0` and `1` in `P₇₉₇`, their positions, and the
adjacency rows.  The lemmas below check the tables against Euler's criterion.
-/

namespace RamseyIncrement
namespace R1212

/-- The common neighbours of `0` and `1`, increasing, `10` bits each. -/
def vtxLit : ℕ := {hex(vtx_lit)}

def vtx (i : ℕ) : ℕ := (vtxLit >>> (10 * i)) &&& 1023

/-- `idx w` is the position of `w` among them (`8` bits each, `255` if absent). -/
def idxLit : ℕ := {hex(idx_lit)}

def idx (w : ℕ) : ℕ := (idxLit >>> (8 * w)) &&& 255

def mask256 : ℕ := {hex(mask256)}

/-- The adjacency rows: bit `j` of `rowH i` is set iff `vtx i ~ vtx j`. -/
def rowsLit : ℕ := {hex(rows_lit)}

def rowH (i : ℕ) : ℕ := (rowsLit >>> (256 * i)) &&& mask256

/-- All 198 vertices. -/
def fullH : ℕ := 2 ^ 198 - 1

/-- Euler's criterion for `797` on natural numbers. -/
def qrB (d : ℕ) : Bool := d != 0 && d ^ 398 % 797 == 1

theorem vtx_lt : ∀ i < 198, vtx i < 797 := by decide +kernel

theorem rowH_spec : ∀ i < 198, ∀ j < 198,
    (rowH i).testBit j = (i != j && qrB ((vtx i + 797 - vtx j) % 797)) := by
  decide +kernel

/-- Every common neighbour of `0` and `1` is listed. -/
theorem idx_spec : ∀ w < 797, qrB w = true → qrB ((w + 796) % 797) = true →
    idx w < 198 ∧ vtx (idx w) = w := by
  decide +kernel

end R1212
end RamseyIncrement
'''
    outputs["H01Data.lean"] = data

    chunks = [list(range(i, len(br), 8)) for i in range(8)]  # interleave for balanced load
    chunks = [list(range(len(br)))[k::8] for k in range(8)]
    names = []
    for k, ids in enumerate(chunks):
        lines = [header, "import RamseyIncrement.R1212.H01Data\n",
                 "-- check the lemmas one at a time: each `decide +kernel` holds a large kernel cache\n"
                 "set_option Elab.async false\n",
                 f"/-! Branches {k} mod 8 of the top level of `noClique rowH 8 fullH`. -/\n",
                 "namespace RamseyIncrement\nnamespace R1212\n"]
        for i in ids:
            lines.append(f"theorem h01_br_{i} : Search.noClique rowH 7 {hex(br[i])} = true := by\n  decide +kernel\n")
        lines.append(f"\n/-- The arguments checked in this file. -/\ndef h01_chunk_{k} : List ℕ :=\n  [" +
                     ",\n   ".join(hex(br[i]) for i in ids) + "]\n")
        nest = "List.forall_mem_nil _"
        for i in reversed(ids):
            nest = f"List.forall_mem_cons.2 ⟨h01_br_{i}, {nest}⟩"
        lines.append(f"\ntheorem h01_chunk_{k}_ok : ∀ x ∈ h01_chunk_{k}, Search.noClique rowH 7 x = true :=\n  {nest}\n")
        lines.append("\nend R1212\nend RamseyIncrement\n")
        outputs[f"H01Branch{k}.lean"] = "\n".join(lines)

    # the glue: branchArgs is the concatenation of the chunks in the original order
    order = sorted(range(len(br)), key=lambda i: (i % 8, i // 8))
    assert [br[i] for i in order] == [br[i] for k in range(8) for i in chunks[k]]
    glue = header + "".join(f"import RamseyIncrement.R1212.H01Branch{k}\n" for k in range(8)) + f'''
/-!
# No `K₈` in `N(0) ∩ N(1)`

The top level of the search is split into the 148 branches checked in
`H01Branch0` … `H01Branch7`.  The branch list below is a permutation of the
order in which `noClique` visits them; `h01_args_perm` checks this.
-/

namespace RamseyIncrement
namespace R1212

theorem h01_args_perm :
    (Search.branchArgs rowH 256 fullH (fullH ^^^ (fullH &&& Search.colourUnion rowH 7 fullH 0))).Perm
      (h01_chunk_0 ++ h01_chunk_1 ++ h01_chunk_2 ++ h01_chunk_3 ++
        h01_chunk_4 ++ h01_chunk_5 ++ h01_chunk_6 ++ h01_chunk_7) := by
  decide +kernel

theorem h01_noK8 : Search.noClique rowH 8 fullH = true := by
  apply Search.noClique_succ_of rowH 7 fullH (by decide +kernel)
  intro x hx
  rw [h01_args_perm.mem_iff] at hx
  simp only [List.mem_append] at hx
  rcases hx with ((((((h | h) | h) | h) | h) | h) | h) | h
  · exact h01_chunk_0_ok x h
  · exact h01_chunk_1_ok x h
  · exact h01_chunk_2_ok x h
  · exact h01_chunk_3_ok x h
  · exact h01_chunk_4_ok x h
  · exact h01_chunk_5_ok x h
  · exact h01_chunk_6_ok x h
  · exact h01_chunk_7_ok x h

end R1212
end RamseyIncrement
'''
    outputs["H01NoK8.lean"] = glue
    return outputs, len(br), [len(c) for c in chunks]


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 1:
        raise SystemExit("usage: gen_h01.py OUTPUT_DIRECTORY")
    outputs, branch_count, chunk_sizes = generate_outputs()
    write_outputs(argv[0], outputs)
    print("branches", branch_count, "chunk sizes", chunk_sizes)


if __name__ == "__main__":
    main()
